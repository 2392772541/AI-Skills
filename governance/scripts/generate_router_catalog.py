from __future__ import annotations

import argparse
from pathlib import Path
from skilllib import load_registry, active_preferred_entries


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate a compact capability catalog for 00-skill-router.")
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    entries = active_preferred_entries(load_registry(args.registry))
    grouped = {}
    for entry in entries:
        for category in entry.get("categories") or ["other"]:
            grouped.setdefault(category, []).append(entry)
    lines = ["# Generated Skill Capability Catalog", "", "Generated by `scripts/generate_router_catalog.py`; do not edit manually.", ""]
    for category in sorted(grouped):
        lines += [f"## {category}", ""]
        for entry in sorted(grouped[category], key=lambda item: item["name"]):
            description = entry.get("description", "").replace("\n", " ")[:180]
            lines.append(f"- `{entry['name']}`: {description}")
        lines.append("")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"catalog={args.output} categories={len(grouped)} skills={len(entries)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())